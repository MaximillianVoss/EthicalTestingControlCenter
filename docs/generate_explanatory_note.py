def add_heading(document: Document, text: str, level: int, md_lines: list[str], *, numbered: bool) -> None:
    style_name = {1: HEADING1_STYLE, 2: HEADING2_STYLE, 3: HEADING3_STYLE}.get(level, HEADING3_STYLE)
    visible_text = strip_number_prefix(text) if numbered else text
    paragraph = document.add_paragraph(visible_text, style=style_name)
    if not numbered:
        suppress_numbering(paragraph)
    if level == 1:
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    md_lines.extend([f'{"#" * level} {text}', ""])


